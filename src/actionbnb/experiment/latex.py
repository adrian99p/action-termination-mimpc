"""Writing generated LaTeX: number macros and tables."""

from math import floor, log10
from pathlib import Path


def sig(value: float, digits: int = 3) -> str:
    """value with `digits` significant figures, without exponent; large values are rounded to integers."""
    if value == 0:
        return "0"
    if abs(value) >= 10 ** (digits - 1):
        return f"{value:.0f}"
    rounded = float(f"{value:.{digits - 1}e}")
    decimals = max(digits - 1 - floor(log10(abs(rounded))), 0)
    return f"{rounded:.{decimals}f}"


def fixed(value: float, decimals: int = 1) -> str:
    """value with a fixed number of decimals, so that both ends of a quoted range match."""
    return f"{value:.{decimals}f}"


def header(source: str, meta: dict | list[dict]) -> str:
    """Comment lines naming the generator and, per results directory, its code commit and run time."""
    lines = [f"% Generated by {source}; do not edit."]
    for m in meta if isinstance(meta, list) else [meta]:
        env = m["environment"]
        dirty = " (dirty)" if env["git_dirty"] else ""
        lines.append(f"% results/{m['experiment']['name']}: commit {env['git_commit']}{dirty}, run {m['started']}.")
    return "\n".join(lines) + "\n"


def write_macros(path: Path, macros: dict[str, str], source: str, meta: dict | list[dict]) -> None:
    """One \\newcommand per macro; names must consist of letters only."""
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macros.items()]
    write(path, header(source, meta) + "\n".join(lines) + "\n")


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
